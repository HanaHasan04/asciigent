"""P6 Experiment: ASCII Animation Generation.

Generates a short N-frame ASCII animation depicting a simple concept (e.g.,
a waving hand, a bouncing ball, a blinking character face).

Approach:
  - Frame 1 is generated with a standalone drawing prompt (like P1/P2).
  - Each subsequent frame is generated by showing frame t to the LLM and asking
    it to produce frame t+1 with visible movement or change.
  - Each frame is saved as ``frame_000.txt`` / ``frame_000.png`` in the run dir.
  - An HTML file ``animation.html`` is produced that plays through the frames in
    a ``<pre>`` tag via JavaScript ``setInterval``.

Usage::

    python -m asciigent.experiments.p6_animate --category cat
    python -m asciigent.experiments.p6_animate --category "bouncing ball" \\
        --frames 6 --fps 4
    python -m asciigent.experiments.p6_animate --dry-run --category cat
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from textwrap import dedent

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from asciigent.grid import DEFAULT_COLS, DEFAULT_ROWS, AsciiGrid
from asciigent.llm import DEFAULT_PROVIDER, LLMClient
from asciigent.prompts.text2ascii import system_prompt as p1_system_prompt
from asciigent.providers import PRESETS, credentials_present, default_model
from asciigent.render import render_to_png_bytes, save_png

# ---------------------------------------------------------------------------
# Prompt builders
# ---------------------------------------------------------------------------

def _frame1_prompt(category: str, n_frames: int, rows: int, cols: int) -> str:
    return (
        f"Draw frame 1/{n_frames} of an ASCII animation of '{category}'. "
        f"This is the first keyframe; draw the starting pose or state clearly "
        f"on the {rows}×{cols} canvas. "
        "Output only the fenced code block containing the drawing."
    )


def _next_frame_prompt(
    category: str,
    frame_num: int,
    n_frames: int,
    prev_grid: AsciiGrid,
) -> str:
    numbered = prev_grid.numbered_text()
    return (
        f"Generate frame {frame_num}/{n_frames} of an ASCII animation of '{category}'. "
        f"Frame {frame_num - 1} is shown below. "
        "Create a variation that shows movement or change "
        "(e.g., slightly different pose, blinking, motion). "
        "Output only the fenced code block containing the drawing.\n\n"
        f"Frame {frame_num - 1} (numbered grid):\n{numbered}"
    )


# ---------------------------------------------------------------------------
# HTML generator
# ---------------------------------------------------------------------------

def _make_animation_html(
    frames: list[str],
    fps: int,
    category: str,
) -> str:
    """Return an HTML string that animates ASCII frames in a <pre> tag."""
    interval_ms = max(1, 1000 // fps)
    frames_json = json.dumps(frames)
    return dedent(f"""\
    <!DOCTYPE html>
    <html lang="en">
    <head>
      <meta charset="UTF-8">
      <title>ASCII Animation: {category}</title>
      <style>
        body {{
          background: #1a1a1a;
          color: #e0e0e0;
          display: flex;
          flex-direction: column;
          align-items: center;
          justify-content: center;
          min-height: 100vh;
          margin: 0;
          font-family: sans-serif;
        }}
        h2 {{ margin-bottom: 0.5em; }}
        pre {{
          font-family: "Consolas", "DejaVu Sans Mono", "Courier New", monospace;
          font-size: 14px;
          line-height: 1.2;
          background: #000;
          padding: 16px;
          border-radius: 4px;
          white-space: pre;
          border: 1px solid #444;
        }}
        #controls {{ margin-top: 1em; }}
        button {{
          padding: 0.4em 1.2em;
          margin: 0 0.3em;
          cursor: pointer;
          border-radius: 3px;
          border: 1px solid #888;
          background: #333;
          color: #e0e0e0;
        }}
        #frame-info {{ color: #888; margin-top: 0.3em; font-size: 0.85em; }}
      </style>
    </head>
    <body>
      <h2>ASCII Animation &mdash; {category}</h2>
      <pre id="canvas">Loading…</pre>
      <div id="controls">
        <button onclick="togglePlay()">⏸ Pause</button>
        <button onclick="stepFrame(-1)">⏮ Prev</button>
        <button onclick="stepFrame(1)">Next ⏭</button>
      </div>
      <div id="frame-info"></div>
      <script>
        const FRAMES = {frames_json};
        const INTERVAL = {interval_ms};
        let idx = 0;
        let playing = true;
        let timer = null;

        function showFrame(i) {{
          idx = ((i % FRAMES.length) + FRAMES.length) % FRAMES.length;
          document.getElementById("canvas").textContent = FRAMES[idx];
          document.getElementById("frame-info").textContent =
            "Frame " + (idx + 1) + " / " + FRAMES.length + "  ·  {fps} fps";
        }}

        function tick() {{ showFrame(idx + 1); }}

        function togglePlay() {{
          playing = !playing;
          if (playing) {{
            timer = setInterval(tick, INTERVAL);
            document.querySelector("button").textContent = "⏸ Pause";
          }} else {{
            clearInterval(timer);
            document.querySelector("button").textContent = "▶ Play";
          }}
        }}

        function stepFrame(delta) {{
          if (playing) togglePlay();
          showFrame(idx + delta);
        }}

        showFrame(0);
        timer = setInterval(tick, INTERVAL);
      </script>
    </body>
    </html>
    """)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--category", default="waving hand",
                    help="Subject/concept to animate, e.g. 'bouncing ball', 'cat'.")
    ap.add_argument("--frames", type=int, default=4,
                    help="Number of frames to generate (default: 4).")
    ap.add_argument("--fps", type=int, default=2,
                    help="Playback speed in frames-per-second for the HTML (default: 2).")
    ap.add_argument("--provider", default=DEFAULT_PROVIDER, choices=sorted(PRESETS))
    ap.add_argument("--model", default=None)
    ap.add_argument("--runs-dir", default="runs")
    ap.add_argument("--dry-run", action="store_true",
                    help="Print configuration and exit without calling the API.")
    args = ap.parse_args(argv)

    if args.frames < 1:
        print("--frames must be at least 1")
        return 1

    model = args.model or default_model(args.provider)
    runs_dir = Path(args.runs_dir)

    print("P6 ASCII Animation")
    print(f"  category : {args.category}")
    print(f"  frames   : {args.frames}")
    print(f"  fps      : {args.fps}")
    print(f"  provider : {args.provider} [{model}]")
    print(f"  runs-dir : {runs_dir}")

    if args.dry_run:
        system = p1_system_prompt(DEFAULT_ROWS, DEFAULT_COLS)
        print(f"\n[dry-run] System prompt preview:\n{system[:300]}")
        print(f"\n[dry-run] Frame 1 prompt:\n{_frame1_prompt(args.category, args.frames, DEFAULT_ROWS, DEFAULT_COLS)[:300]}")
        print("\n[dry-run] Configuration validated successfully.")
        return 0

    if not credentials_present(args.provider):
        cfg = PRESETS[args.provider]
        print(f"No credentials found for {args.provider}. Please set ${cfg.key_env}")
        return 2

    # -- Setup ----------------------------------------------------------------
    run_subdir = runs_dir / "p6_animate"
    run_subdir.mkdir(parents=True, exist_ok=True)

    client = LLMClient(provider=args.provider, model=model)
    system = p1_system_prompt(DEFAULT_ROWS, DEFAULT_COLS)

    grids: list[AsciiGrid] = []

    # -- Generate frames ------------------------------------------------------
    for f in range(1, args.frames + 1):
        print(f"\nGenerating frame {f}/{args.frames} …")

        if f == 1:
            prompt = _frame1_prompt(args.category, args.frames, DEFAULT_ROWS, DEFAULT_COLS)
            images: list[bytes] = []
        else:
            prev_grid = grids[-1]
            # Pass the rendered previous frame as an image for visual grounding
            prev_png = render_to_png_bytes(prev_grid)
            prompt = _next_frame_prompt(args.category, f, args.frames, prev_grid)
            images = [prev_png]

        resp = client.complete(
            prompt=prompt,
            images=images,
            system=system,
            sample_index=f,  # distinct cache keys per frame
        )

        grid, report = AsciiGrid.from_text(resp.text, rows=DEFAULT_ROWS, cols=DEFAULT_COLS)
        if not report.clean:
            print(f"  Parse issues: {report.issues}")
        print(f"  ink_ratio={grid.ink_ratio():.3f}")
        grids.append(grid)

        # Persist frame
        frame_name = f"frame_{f - 1:03d}"
        (run_subdir / f"{frame_name}.txt").write_text(grid.to_text(), encoding="ascii")
        save_png(grid, str(run_subdir / f"{frame_name}.png"))
        print(f"  Saved {frame_name}.txt/.png")

    # -- Generate HTML --------------------------------------------------------
    frame_texts = [g.to_text() for g in grids]
    html = _make_animation_html(frame_texts, args.fps, args.category)
    html_path = run_subdir / "animation.html"
    html_path.write_text(html, encoding="utf-8")

    print(f"\nAnimation saved to : {run_subdir}")
    print(f"Open in browser    : {html_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
